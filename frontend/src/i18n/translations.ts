const zhPatterns: Array<[RegExp, (...values: string[]) => string]> = [
  [/^Incorrect verification code\. (\d+) attempts remaining\.$/, (count) => `验证码错误，还可以尝试 ${count} 次。`],
  [/^Welcome back, (.+)!$/, (name) => `欢迎回来，${name}！`],
  [/^(\d+) tasks$/, (count) => `${count} 个任务`],
  [/^(\d+) tests$/, (count) => `${count} 项测试`],
  [/^(\d+) test files?$/, (count) => `${count} 个测试文件`],
  [/^(\d+) cases?$/, (count) => `${count} 个用例`],
  [/^(\d+) runs?$/, (count) => `${count} 次运行`],
  [/^([\d.]+) score$/, (score) => `${score} 分`],
  [/^(\d+) members?$/, (count) => `${count} 名成员`],
  [/^Delete selected \((\d+)\)$/, (count) => `删除所选项（${count}）`],
  [/^Select (.+)$/, (name) => `选择 ${name}`],
  [/^Download (.+)$/, (name) => `下载 ${name}`],
  [/^(\d+) selected runs? deleted\.$/, (count) => `已删除 ${count} 条所选运行。`],
  [/^(\d+) runs? could not be deleted and remain selected\.$/, (count) => `${count} 条运行无法删除，仍保持选中。`],
  [/^Dependency added: (.+) -> (.+)$/, (source, target) => `已添加依赖：${source} → ${target}`],
  [/^(.+) command sent to (.+)\.$/, (action, executor) => `已向 ${executor} 发送 ${action} 命令。`],
];

export function translateUiText(value: string, language: Language): string {
  if (language === "en") return value;
  const exact = zhTranslations[value];
  if (exact) return exact;
  for (const [pattern, formatter] of zhPatterns) {
    const match = value.match(pattern);
    if (match) return formatter(...match.slice(1));
  }
  return value;
}
